// A trampoline "shape" describes how a command's arguments are passed at the machine level. Each argument is one of:
//
//	'i' - integer class: any integer, enum, bitmask, handle, or pointer
//	'f' - float (32 bit)
//	'd' - double (64 bit)
//
// The shape is the ordered string of those classes, e.g. vkCmdSetDepthBias(VkCommandBuffer, float, float, float) is
// "ifff". Order matters because some ABIs (Win64) assign argument registers by position, while others (SysV x86-64,
// AAPCS64) allocate integer and floating point registers independently; keeping the full order is correct for both.
//
// Floats cannot be passed through an all-integer trampoline: the callee reads them from a floating point register,
// but an integer-typed call puts the bits in an integer register. Each distinct shape therefore gets its own C
// trampoline, with correspondingly typed parameters, that casts the function pointer to the true signature before
// calling it. A typed Go wrapper (vkCall_<shape>) calls each trampoline through cgo.
const (
	classInt    byte = 'i'
	classFloat  byte = 'f'
	classDouble byte = 'd'
)

// abiClassOf returns the argument class a TypeDefiner decays to when passed by value to a C function.
func abiClassOf(td TypeDefiner) (byte, error) {
	switch td.Category() {
	case CatPointer, CatHandle, CatEnum, CatBitmask:
		return classInt, nil

	case CatBasetype:
		// Base types are typedefs of an external (primitive) type
		if bt, ok := td.(*baseType); ok && bt.resolvedUnderlyingType != nil {
			return abiClassOf(bt.resolvedUnderlyingType)
		}
		return 0, fmt.Errorf("base type %s has no resolved underlying type", td.RegistryName())

	case CatExternal:
		switch td.RegistryName() {
		case "float":
			return classFloat, nil
		case "double":
			return classDouble, nil
		}
		return classInt, nil
	}

	return 0, fmt.Errorf("type %s (%s) cannot be classified for passing by value to a command", td.RegistryName(), td.Category())
}

// shapeOfParams builds the shape string for a command's trampoline parameters.
func shapeOfParams(params []*commandParam) (string, error) {
	sb := &strings.Builder{}
	for _, p := range params {
		c, err := abiClassOf(p.resolvedType)
		if err != nil {
			return "", fmt.Errorf("parameter %s: %w", p.registryName, err)
		}
		sb.WriteByte(c)
	}
	return sb.String(), nil
}

// usedShapes is the set of shapes needed by all commands printed so far. Trampoline source is generated for exactly
// this set by WriteTrampolineFiles, which must be called after all commands have been printed.
var usedShapes = map[string]bool{}

func registerShape(shape string) { usedShapes[shape] = true }

// shapeSuffix is the name fragment for a shape's functions. An empty shape (no arguments) cannot be part of an
// identifier.
func shapeSuffix(shape string) string {
	if shape == "" {
		return "none"
	}
	return shape
}

func trampFuncName(shape string) string { return "vkTramp_" + shapeSuffix(shape) }
func callFuncName(shape string) string  { return "vkCall_" + shapeSuffix(shape) }

func cTypeForClass(c byte) string {
	switch c {
	case classFloat:
		return "float"
	case classDouble:
		return "double"
	}
	return "uintptr_t"
}

func goTypeForClass(c byte) string {
	switch c {
	case classFloat:
		return "float32"
	case classDouble:
		return "float64"
	}
	return "uintptr"
}

func cgoTypeForClass(c byte) string {
	switch c {
	case classFloat:
		return "C.float"
	case classDouble:
		return "C.double"
	}
	return "C.uintptr_t"
}

func sortedShapes() []string {
	shapes := make([]string, 0, len(usedShapes))
	for s := range usedShapes {
		shapes = append(shapes, s)
	}
	slices.Sort(shapes)
	return shapes
}

func cTrampSignature(shape string) string {
	sb := &strings.Builder{}
	fmt.Fprintf(sb, "uintptr_t %s(void *fn", trampFuncName(shape))
	for i := range shape {
		fmt.Fprintf(sb, ", %s p%d", cTypeForClass(shape[i]), i)
	}
	sb.WriteString(")")
	return sb.String()
}

// trampolineSources are the generated contents of trampolines.h, trampolines.c, and shapes.go.
type trampolineSources struct {
	header, c string
	goWrapper []byte
}

// renderTrampolineSources builds trampoline source for the given (sorted) shapes.
func renderTrampolineSources(shapes []string) (trampolineSources, error) {
	const header = "// Code generated by vk-gen. DO NOT EDIT.\n\n"

	// Header
	h := &strings.Builder{}
	h.WriteString(header)
	h.WriteString("#ifndef __TRAMPOLINES_H__\n#define __TRAMPOLINES_H__\n\n#include <stdint.h>\n\n")
	for _, s := range shapes {
		fmt.Fprintf(h, "%s;\n", cTrampSignature(s))
	}
	h.WriteString("\n#endif\n")

	// C source
	c := &strings.Builder{}
	c.WriteString(header)
	c.WriteString("#include <stdint.h>\n#include <string.h>\n#include \"trampolines.h\"\n\n")
	c.WriteString("// Each trampoline casts the function pointer to the callee's true signature, so that floats and doubles are passed\n")
	c.WriteString("// in floating point registers, per the platform calling convention.\n\n")
	for _, s := range shapes {
		types := make([]string, len(s))
		args := make([]string, len(s))
		for i := range s {
			types[i] = cTypeForClass(s[i])
			args[i] = fmt.Sprintf("p%d", i)
		}
		fmt.Fprintf(c, "%s {\n", cTrampSignature(s))
		fmt.Fprintf(c, "\treturn ((uintptr_t (*)(%s))fn)(%s);\n}\n\n", cParamList(types), strings.Join(args, ", "))
	}

	// Go wrappers
	g := &strings.Builder{}
	g.WriteString(header)
	g.WriteString("package vk\n\n// #include \"trampolines.h\"\nimport \"C\"\n\n")
	for _, s := range shapes {
		params := []string{"cmd *vkCommand"}
		args := []string{"cmd.resolve()"}
		for i := range s {
			params = append(params, fmt.Sprintf("p%d %s", i, goTypeForClass(s[i])))
			args = append(args, fmt.Sprintf("%s(p%d)", cgoTypeForClass(s[i]), i))
		}
		// Commands pass pointers to Go memory as uintptr(unsafe.Pointer(x)). Without this directive, such an argument
		// neither keeps its target alive while C runs (the GC may free it mid-call) nor stops the target from living on
		// a goroutine stack that can be moved before the C call begins. //go:uintptrescapes makes the compiler keep the
		// pointer alive for the duration of the call and move its target to the heap. It requires that the
		// unsafe.Pointer to uintptr conversion appear in the argument list of every call, which generated commands do.
		fmt.Fprintf(g, "// %s calls %s through cgo.\n//\n//go:uintptrescapes\n", callFuncName(s), trampFuncName(s))
		fmt.Fprintf(g, "func %s(%s) uintptr {\n", callFuncName(s), strings.Join(params, ", "))
		fmt.Fprintf(g, "\treturn uintptr(C.%s(%s))\n}\n\n", trampFuncName(s), strings.Join(args, ", "))
	}
	gSrc, err := format.Source([]byte(g.String()))
	if err != nil {
		return trampolineSources{}, fmt.Errorf("could not format generated trampoline wrappers: %w", err)
	}

	return trampolineSources{header: h.String(), c: c.String(), goWrapper: gSrc}, nil
}

// WriteTrampolineFiles generates trampolines.h, trampolines.c, and shapes.go into dir. Every shape registered while
// printing commands gets a C trampoline and a Go wrapper that calls it through cgo.
func WriteTrampolineFiles(dir string) {
	shapes := sortedShapes()

	src, err := renderTrampolineSources(shapes)
	if err != nil {
		logrus.WithField("error", err).Fatal("Could not generate trampoline source")
	}

	for name, content := range map[string][]byte{
		"trampolines.h": []byte(src.header),
		"trampolines.c": []byte(src.c),
		"shapes.go":     src.goWrapper,
	} {
		if err := os.WriteFile(filepath.Join(dir, name), content, 0666); err != nil {
			logrus.WithField("error", err).WithField("file", name).Fatal("Could not write trampoline file")
		}
	}

	logrus.WithField("shapes", shapes).Infof("Generated %d trampoline shapes", len(shapes))
}

func cParamList(types []string) string {
	if len(types) == 0 {
		return "void"
	}
	return strings.Join(types, ", ")
}
